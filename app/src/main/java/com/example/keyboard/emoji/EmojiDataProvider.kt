package com.example.keyboard.emoji

import android.content.Context
import android.content.SharedPreferences

object EmojiDataProvider {

    private const val PREFS_NAME = "emoji_recents_prefs"
    private const val KEY_RECENTS = "recent_emojis"
    private const val MAX_RECENTS = 35

    fun getRecents(context: Context): List<String> {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val saved = prefs.getString(KEY_RECENTS, null) ?: return getDefaultRecents()
        return saved.split(",").filter { it.isNotBlank() }
    }

    fun addRecent(context: Context, emoji: String) {
        val current = getRecents(context).toMutableList()
        current.remove(emoji)
        current.add(0, emoji)
        if (current.size > MAX_RECENTS) {
            current.subList(MAX_RECENTS, current.size).clear()
        }
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        prefs.edit().putString(KEY_RECENTS, current.joinToString(",")).apply()
    }

