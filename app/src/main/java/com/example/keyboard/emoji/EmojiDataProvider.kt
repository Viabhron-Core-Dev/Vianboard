    fun searchEmojis(query: String): List<String> {
        val q = query.lowercase().trim()
        if (q.isEmpty()) return emptyList()
        val results = mutableSetOf<String>()
        for ((tag, list) in KEYWORD_TAGS) {
            if (tag.contains(q) || q.contains(tag)) {
                results.addAll(list)
            }
        }
        return results.toList()
    }

    private val SKIN_TONES = listOf("\uD83C\uDFFB", "\uD83C\uDFFC", "\uD83C\uDFFD", "\uD83C\uDFFE", "\uD83C\uDFFF")

    fun getSkinToneVariations(baseEmoji: String): List<String>? {
        if (!PEOPLE.contains(baseEmoji)) return null
        return listOf(baseEmoji) + SKIN_TONES.map { tone -> baseEmoji + tone }
    }
